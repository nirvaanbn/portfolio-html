"""
Generates css/marketing-layout.css from the Canva mockup's measurements.

Measured off "Pages for Portfolio/mkt-assets-hq2.png" -- the high-quality
1920x1080 export. Canvas is 1920 wide like every other page, so a canvas pixel
maps to the same screen pixel here as on the landing page, which is what keeps
the stars lined up across the transition. Re-run after changing anything below:

    python tools/build_marketing_css.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 1920.0, 1080.0

# ---- measured from mkt-assets-hq2.png (x, y, w, h) -----------------------
MOUNTAIN_L = (1, 22, 632, 276)
MOUNTAIN_R = (1234, 0, 685, 278)   # 278 after the dangling stroke was trimmed
FLAG = (1321, 67, 61, 81)
TITLE = (487, 98, 802, 30)      # ink box; sits left of centre to leave room for the flag
BOX1 = (107, 227, 708, 167)
BOX2 = (107, 432, 709, 622)
# --- photo grid -----------------------------------------------------------
# The right-hand cluster now mirrors the copy's margin: the text box starts
# 107px from the left edge, so the photos finish 107px from the right (x1813).
# The columns keep the mockup's arrangement and proportions, but are laid out
# here rather than hard-coded, so the scale can be driven up to whatever the
# vertical band allows.
PHOTO_L, PHOTO_R = 872.0, 1813.0     # 1813 = 1920 - 107, mirroring the text
PHOTO_TOP, PHOTO_BOT = 188.0, 1055.0   # one line (28px) below the title
PHOTO_GAP_V = 20.0
PORTRAIT, LANDSCAPE = (191.0, 222.0), (294.0, 252.0)   # design proportions
# column -> the photos in it, top to bottom (index into PHOTOS order)
COLUMNS = [[(1, PORTRAIT), (4, LANDSCAPE), (7, PORTRAIT)],
           [(3, PORTRAIT), (6, PORTRAIT)],
           [(2, PORTRAIT), (5, PORTRAIT), (8, PORTRAIT)]]
# The pin marks the Machapuchare summit inside photo 4. It is anchored as a
# fraction of that photo so it tracks the photo wherever the grid puts it, and
# it is placed by its TIP (bottom centre), which is the point that must land on
# the peak. Drawn as SVG so it stays perfectly round at any size.
PIN_ON_PHOTO = 4
PIN_PEAK = (0.322, 0.432)      # the summit, as a fraction of photo 4
PIN_W = 46.0                   # canvas px; the SVG is 24x32, so height follows
# the landing page's own star position, kept so the hand-off stays seamless
STAR_TITLE = (246, 66, 76, 76)

BOX_RADIUS, BOX_PAD, BOX_FILL = 18.0, 26.0, "#f5ebce"

# ---- type ---------------------------------------------------------------
# Title: 42px reproduces the mockup's ink width (802px) almost exactly, which
# is what matters here -- it decides where the word DEVELOPMENT ends and so
# whether the flag sits correctly beside it.
F_TITLE = 42.0
TITLE_TRACK = "0"
# Body: this design's boxes are smaller than the previous export's, and the
# copy simply does not fit at the old size -- 24px overflows both boxes. 22px
# lands box 1 on four lines with room to spare and leaves box 2 comfortable.
F_BODY = 22.0
LEADING = 28.0
BOX1_TRACK, BOX2_TRACK = "0", "0"

# ---- entrance timing ----------------------------------------------------
PHASE1_DUR = 1.2                 # mountains + title, alone
PHASE2_START, FADE = 1.0, 0.9    # everything else, together
PIN_DELAY, PIN_DUR = 2.05, 0.7   # the pin springs up last


def X(v): return f"{v / W * 100:.4f}%"
def Y(v): return f"{v / H * 100:.4f}%"
def vw(px): return f"{px / W * 100:.4f}vw"


o = []
a = o.append
a("/* ============================================================")
a("   MARKETING CAMPAIGN DEVELOPMENT page")
a("   GENERATED by tools/build_marketing_css.py -- edit that, not this.")
a(f"   Canvas {int(W)}x{int(H)}, measured from mkt-assets-hq2.png.")
a("   ============================================================ */")
a(".mkt-stage {")
a("  position: relative;")
a("  width: 100%;")
a(f"  aspect-ratio: {int(W)} / {int(H)};")
a("  margin: 0 auto;")
a("  overflow: hidden;")
a("  /* the stars sit exactly where the landing page leaves them, so the")
a("     hand-off after the fade-out is invisible */")
a('  background: url("../assets/layer-stars.png") top left / 100% auto no-repeat #160c0f;')
a("}")
a(".mkt-stage > * { position: absolute; margin: 0; }")
a("")
a("/* the star the landing page keeps on screen, drawn here so it does not move */")
a(f".mkt-star {{ left: {X(STAR_TITLE[0])}; top: {Y(STAR_TITLE[1])}; "
  f"width: {X(STAR_TITLE[2])}; height: {Y(STAR_TITLE[3])};")
a('             background: url("../assets/layer-star-title.png") center / 100% 100% no-repeat; }')
a("")
a("/* ---------- artwork ---------- */")
a(".mkt-art { background: center / 100% 100% no-repeat; pointer-events: none; }")
for name, (x, y, w, h), img in (("mkt-mtn-l", MOUNTAIN_L, "mkt-mountain-left.png"),
                                ("mkt-mtn-r", MOUNTAIN_R, "mkt-mountain-right.png"),
                                ("mkt-flag", FLAG, "mkt-flag.png")):
    a(f".{name} {{ left: {X(x)}; top: {Y(y)}; width: {X(w)}; height: {Y(h)};")
    a(f'          background-image: url("../assets/{img}"); }}')
a("")
a("/* ---------- title ---------- */")
a("/* left-aligned rather than centred: the mockup sets it off to the left so")
a("   the flag can sit at the end of the word DEVELOPMENT */")
a(".mkt-title {")
a(f"  left: {X(TITLE[0])}; top: {Y(TITLE[1] - F_TITLE * 0.1755)};   /* 0.1755em = Times cap-top offset at line-height 1 */")
a("  white-space: nowrap;")
a("  font-family: var(--font-serif); font-weight: 400;")
a(f"  text-transform: uppercase; letter-spacing: {TITLE_TRACK};")
a(f"  font-size: {vw(F_TITLE)}; line-height: 1; color: #ffffff;")
a("}")
a("")
a("/* ---------- copy boxes ---------- */")
a("/* drawn in CSS rather than as images so the text stays editable and wraps.")
a("   Padding is even on all four sides and the block is centred vertically, so")
a("   the copy sits in the middle of the box rather than hugging an edge. */")
a(".mkt-box {")
a("  box-sizing: border-box;")
a(f"  background: {BOX_FILL};")
a(f"  border-radius: {vw(BOX_RADIUS)};")
a(f"  padding: {vw(BOX_PAD)};")
a("  height: auto;")
a("  color: #1a1a1a;")
a("  font-family: var(--font-serif);")
a(f"  font-size: {vw(F_BODY)}; line-height: {LEADING / F_BODY:.4f};")
a("}")
a(f".mkt-box p {{ margin: 0 0 {LEADING / F_BODY:.4f}em; }}")
a(".mkt-box p:last-child { margin-bottom: 0; }")
a("/* Canva tracked the two boxes differently; these keep each box wrapping")
a("   on sensible words and filling its height. */")
a(f".mkt-box1 {{ letter-spacing: {BOX1_TRACK}; }}")
a(f".mkt-box2 {{ letter-spacing: {BOX2_TRACK}; }}")
# height is left to the content: fixed heights left box 1 nearly overflowing
# and box 2 half empty, which is what made the cream shapes look mismatched.
for name, (x, y, w, h) in (("mkt-box1", BOX1), ("mkt-box2", BOX2)):
    a(f".{name} {{ left: {X(x)}; top: {Y(y)}; width: {X(w)}; }}")
a("")
a("/* ---------- polaroids + the map pin ---------- */")
a(".mkt-photo { background: center / 100% 100% no-repeat; }")
# scale is whatever the vertical band allows for the tallest column
tallest = max(sum(h for _, (w, h) in col) for col in COLUMNS)
most = max(len(col) for col in COLUMNS)
K = (PHOTO_BOT - PHOTO_TOP - (most - 1) * PHOTO_GAP_V) / tallest
col_w = [max(w for _, (w, h) in col) * K for col in COLUMNS]
gap_h = (PHOTO_R - PHOTO_L - sum(col_w)) / (len(COLUMNS) - 1)
rects = {}
cx = PHOTO_L
for col, cw in zip(COLUMNS, col_w):
    span = sum(h for _, (w, h) in col) * K + (len(col) - 1) * PHOTO_GAP_V
    cy = PHOTO_TOP + (PHOTO_BOT - PHOTO_TOP - span) / 2      # centre the column
    for idx, (w, h) in col:
        pw, ph = w * K, h * K
        rects[idx] = (cx + (cw - pw) / 2, cy, pw, ph)        # centre in its column
        cy += ph + PHOTO_GAP_V
    cx += cw + gap_h
for i in sorted(rects):
    x, y, w, h = rects[i]
    a(f".mkt-photo-{i} {{ left: {X(x)}; top: {Y(y)}; width: {X(w)}; height: {Y(h)};")
    a(f'                  background-image: url("../assets/mkt-photo-{i}.png"); }}')
px, py, pw, ph = rects[PIN_ON_PHOTO]
pin_h = PIN_W * 32.0 / 24.0
peak_x, peak_y = px + PIN_PEAK[0] * pw, py + PIN_PEAK[1] * ph
PIN = (peak_x - PIN_W / 2, peak_y - pin_h, PIN_W, pin_h)   # tip lands on the peak
a(f".mkt-pin {{ left: {X(PIN[0])}; top: {Y(PIN[1])}; width: {X(PIN[2])}; height: {Y(PIN[3])};")
a('           background: url("../assets/mkt-pin.svg") center / 100% 100% no-repeat;')
a("           cursor: pointer;")
a("           transition: filter 0.2s ease, transform 0.2s ease; }")
a(".mkt-pin:hover, .mkt-pin:focus-visible { filter: brightness(1.15); transform: scale(1.08); }")
a("")
a("/* ============================================================")
a("   Entrance. The mountains and title come up alone first; about a")
a("   second later everything else fades in together; the pin lands last.")
a("   ============================================================ */")
a("@keyframes mkt-in { from { opacity: 0; } to { opacity: 1; } }")
a("/* beat 1: the header -- mountains, title and flag together */")
a(f".mkt-stage .mkt-art, .mkt-stage .mkt-title {{ animation: mkt-in {PHASE1_DUR}s ease both; }}")
a("/* beat 2: the boxes and photos, together */")
second = ["mkt-box1", "mkt-box2"] + [f"mkt-photo-{i}" for i in sorted(rects)]
a(", ".join(f".mkt-stage .{n}" for n in second) + " {")
a(f"  animation: mkt-in {FADE}s ease {PHASE2_START}s both;")
a("}")
a("")
a("/* beat 3: the pin springs up from its own point. fill-mode is backwards,")
a("   not both, so once it settles the element returns to its normal styles")
a("   and the hover transform still works. */")
a("@keyframes mkt-pin-pop {")
a("  0%   { opacity: 0; transform: translateY(-45%) scale(0.4); }")
a("  55%  { opacity: 1; transform: translateY(0) scale(1.18); }")
a("  75%  { transform: translateY(0) scale(0.94); }")
a("  90%  { transform: translateY(0) scale(1.04); }")
a("  100% { opacity: 1; transform: translateY(0) scale(1); }")
a("}")
a(".mkt-pin {")
a("  transform-origin: 50% 100%;   /* the tip: it springs up from where it points */")
a(f"  animation: mkt-pin-pop {PIN_DUR}s cubic-bezier(0.34, 1.4, 0.64, 1) {PIN_DELAY}s backwards;")
a("}")
a("")
a("@media (prefers-reduced-motion: reduce) {")
a("  .mkt-stage *, .mkt-stage { animation: none !important; }")
a("}")

open(os.path.join(ROOT, "css", "marketing-layout.css"), "w", encoding="utf-8").write("\n".join(o) + "\n")
print(f"canvas {int(W)}x{int(H)}   title {F_TITLE}px   body {F_BODY}px / {LEADING}px leading")
print(f"beat 1: mountains + title      0 -> {PHASE1_DUR}s")
print(f"beat 2: {len(second)} elements together  {PHASE2_START} -> {PHASE2_START + FADE}s")
print(f"beat 3: pin springs up         {PIN_DELAY} -> {PIN_DELAY + PIN_DUR}s")
print(f"photo scale {K:.3f}x  portrait {191*K:.0f}x{222*K:.0f}  landscape {294*K:.0f}x{252*K:.0f}")
print(f"photo band x{PHOTO_L:.0f}-{PHOTO_R:.0f} (right margin {1920-PHOTO_R:.0f} = text left margin {BOX1[0]:.0f}), column gap {gap_h:.0f}")
print(f"photo band top y{PHOTO_TOP:.0f}; pin tip on the peak at ({peak_x:.0f}, {peak_y:.0f})")
print("wrote css/marketing-layout.css")
