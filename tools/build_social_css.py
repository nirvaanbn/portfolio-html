"""
Generates css/social.css -- the Social Media page layout.

Everything sits on the mockup's 1920-wide canvas and is emitted as a
percentage of it, so the design keeps its proportions at any window size.
Rather than hard-coding the mockup's original boxes, the rows are laid out
here: pick a content band and a gap, and the box scale falls out of the
arithmetic. Re-run after changing anything below:

    python tools/build_social_css.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = 1920.0

# ---------------------------------------------------------------- layout knobs
BAND_L, BAND_R = 200.0, 1720.0     # content band, centred on the canvas (960)
                                   # left edge clears the star at x108-184
PERSONAL_GAP = 32.0                # the tighter row decides the box scale
CANVAS_H = 2558.0

# base box sizes from the Canva mockup (portrait 9:16, landscape 16:9)
B_BOXES = [225.0, 578.0, 226.0, 225.0]        # brand row
P_BOXES = [225.0, 225.0, 579.0]               # personal row
LOGO_TIKTOK, LOGO_YOUTUBE = 141.0, 124.0      # kept at design size
PORTRAIT_H, LANDSCAPE_H = 397.0, 327.0

# vertical rhythm (ink positions, canvas px) -- pulled up hard so the personal
# row lands in the first screenful. The title now sits over the top-left star
# cluster (y66-142) by design; that overlap is what buys the extra 90px.
TITLE_TOP = 60.0
BRANDS_LABEL_TOP = 204.0   # a full line clear of the title
ESPANOL_TOP = 264.0
BRAND_TOP = 324.0
CAPTION_DROP = 42.0                # box bottom -> caption ink centre
PERSONAL_LABEL_TOP = 869.0
PERSONAL_TOP = 969.0
BACKGROUND_LABEL_TOP = 1568.0   # one line lower than the row above
COPY_TOP = 1674.0
PHONE = (1342.0, 1680.0, 367.0, 725.0)
ARROW = (1750.0, 70.0)             # x, size; sits in the right margin

# type sizes (pt on the mockup; 1pt = 1.448px on this canvas)
PT = 1.448
F_TITLE, F_LABEL, F_CAPTION, F_ESPANOL, F_COPY = 50 * PT, 35 * PT, 29 * PT, 22 * PT, 26 * PT
LEADING = 54.0

BAND_W = BAND_R - BAND_L
# the personal row is the crowded one, so it sets the scale for both rows
K = (BAND_W - (LOGO_TIKTOK + LOGO_YOUTUBE) - 4 * PERSONAL_GAP) / sum(P_BOXES)
BRAND_GAP = (BAND_W - sum(B_BOXES) * K) / (len(B_BOXES) - 1)

def X(v): return f"{v / W * 100:.4f}%"
def Y(v): return f"{v / CANVAS_H * 100:.4f}%"
def vw(px): return f"{px / W * 100:.4f}vw"

def row(boxes, gap, start=BAND_L):
    """Left edge and width of each item in a row, in canvas px."""
    out, x = [], start
    for b in boxes:
        out.append((x, b))
        x += b + gap
    return out

brand = row([b * K for b in B_BOXES], BRAND_GAP)
personal = row([P_BOXES[0] * K, P_BOXES[1] * K, LOGO_TIKTOK, P_BOXES[2] * K, LOGO_YOUTUBE],
               PERSONAL_GAP)

P_H, L_H = PORTRAIT_H * K, LANDSCAPE_H * K            # scaled box heights
def land_top(row_top): return row_top + (P_H - L_H) / 2   # landscape sits centred

o = []
a = o.append
a("/* ============================================================")
a("   SOCIAL MEDIA + CONTENT CREATION page")
a("   GENERATED by tools/build_social_css.py -- edit that, not this.")
a(f"   Canvas {int(W)}x{int(CANVAS_H)}. Content band x{BAND_L:.0f}-{BAND_R:.0f}")
a(f"   (centred on {W/2:.0f}); box scale {K:.4f}x the mockup.")
a("   ============================================================ */")
a(".social-stage {")
a("  /* --soc-scale shrinks the whole layout, stars excluded, so more lands in")
a("     the first screenful. Raise it for bigger videos, lower it to see more. */")
a("  --soc-scale: 1;")
a("  position: relative;")
a("  width: 100%;")
a(f"  aspect-ratio: {int(W)} / calc({int(CANVAS_H)} * var(--soc-scale));")
a("  margin: 0 auto;")
a("  /* the stars sit where they do on the landing page, which is what makes")
a("     the fade-out hand-off between the two pages invisible */")
a('  background: url("../assets/layer-stars.png") top left / 100% auto no-repeat #160c0f;')
a("}")
a(".social-canvas {")
a("  position: absolute; top: 0; left: 0;")
a("  width: 100%;")
a(f"  aspect-ratio: {int(W)} / {int(CANVAS_H)};")
a("  transform: scale(var(--soc-scale));")
a("  transform-origin: 50% 0;")
a("}")
a(".social-canvas > * { position: absolute; margin: 0; }")
a("")
a("/* ---------- headings and labels ---------- */")
a(".soc-title {")
a(f"  left: {X(BAND_L)}; top: {Y(TITLE_TOP)};")
a("  font-family: var(--font-agrandir); font-weight: 400;")
a("  text-transform: uppercase; letter-spacing: 0.005em;")
a(f"  font-size: {vw(F_TITLE)}; line-height: 1; color: #fff;      /* 50pt */")
a("}")
a(".soc-label {")
a("  font-family: var(--font-agrandir); font-weight: 400;")
a(f"  font-size: {vw(F_LABEL)}; line-height: 1; color: #fff;      /* 35pt */")
a("}")
a(f".soc-label-brands     {{ left: {X(BAND_L + 100)}; top: {Y(BRANDS_LABEL_TOP)}; }}")
a(f".soc-label-personal   {{ left: {X(BAND_L + 125)}; top: {Y(PERSONAL_LABEL_TOP)}; }}")
a(f".soc-label-background {{ left: {X(BAND_L + 125)}; top: {Y(BACKGROUND_LABEL_TOP)}; }}")
# "en espanol" is centred over the third video
esp_c = brand[2][0] + brand[2][1] / 2
a(".soc-note {")
a("  font-family: var(--font-serif); color: #f1ede4;")
a(f"  font-size: {vw(F_ESPANOL)}; line-height: 1;                 /* 22pt */")
a("  transform: translateX(-50%);")
a("}")
a(f".soc-note-espanol {{ left: {X(esp_c)}; top: {Y(ESPANOL_TOP)}; }}")
a("")
a("/* ---------- video frames ---------- */")
a("/* the white border belongs to the frame, so it survives once the poster")
a("   (and later the player) is inside it */")
a(".soc-frame {")
a("  width: 100%; height: 100%;")
a("  box-sizing: border-box;")
a("  border: max(1px, 0.156vw) solid #fff;   /* 3px on the mockup canvas */")
a("  background: #000;")
a("  overflow: hidden;")
a("}")
a(".soc-item figcaption {")
a("  position: absolute; left: 50%; transform: translate(-50%, -50%);")
a("  white-space: nowrap;")
a("  font-family: var(--font-serif); color: #f1ede4;")
a(f"  font-size: {vw(F_CAPTION)}; line-height: 1;                 /* 29pt */")
a("}")

def emit(name, x, w, top, h, cap_centre):
    a(f".soc-{name} {{ left: {X(x)}; top: {Y(top)}; width: {X(w)}; height: {Y(h)}; }}")
    a(f".soc-{name} figcaption {{ top: {(cap_centre - top) / h * 100:.4f}%; }}")

b_cap = BRAND_TOP + P_H + CAPTION_DROP
for i, (x, w) in enumerate(brand):
    landscape = (i == 1)
    emit(f"b{i+1}", x, w, land_top(BRAND_TOP) if landscape else BRAND_TOP,
         L_H if landscape else P_H, b_cap)
p_cap = PERSONAL_TOP + P_H + CAPTION_DROP
for name, idx in (("p1", 0), ("p2", 1), ("p3", 3)):
    x, w = personal[idx]
    landscape = (name == "p3")
    emit(name, x, w, land_top(PERSONAL_TOP) if landscape else PERSONAL_TOP,
         L_H if landscape else P_H, p_cap)
a("")
a("/* ---------- logos and the decorative arrow ---------- */")
a(".soc-logo { background: center / 100% 100% no-repeat; }")
row_mid = PERSONAL_TOP + P_H / 2
for name, idx, h, img in (("tiktok", 2, LOGO_TIKTOK, "social-tiktok.png"),
                          ("youtube", 4, 88.0, "social-youtube.png")):
    x, w = personal[idx]
    a(f".soc-logo-{name} {{ left: {X(x)}; top: {Y(row_mid - h/2)}; "
      f"width: {X(w)}; height: {Y(h)};")
    a(f'                     background-image: url("../assets/{img}"); }}')
a(".soc-logo:hover, .soc-logo:focus-visible { filter: brightness(1.2); }")
a(".soc-arrow {")
a(f"  left: {X(ARROW[0])}; top: {Y(BRAND_TOP + P_H/2 - ARROW[1]/2)}; "
  f"width: {X(ARROW[1])}; aspect-ratio: 1;")
a("  border-radius: 50%; background: #f4f4f4;")
a("}")
a(".soc-arrow::after {")
a('  content: ""; position: absolute; left: 44%; top: 50%;')
a("  width: 26%; height: 26%;")
a("  border-right: 0.18vw solid #4a4a4a; border-top: 0.18vw solid #4a4a4a;")
a("  transform: translate(-50%, -50%) rotate(45deg);")
a("}")
a("")
a("/* ---------- background copy ---------- */")
a(".soc-copy {")
a(f"  left: {X(228)}; top: {Y(COPY_TOP)}; width: {X(1020)};")
a("  font-family: var(--font-serif); color: #f1ede4;")
a(f"  font-size: {vw(F_COPY)}; line-height: {LEADING/F_COPY:.4f};  /* 26pt */")
a("  /* the Canva text is tracked out; without this it wraps ~10% short */")
a("  letter-spacing: 0.034em;")
a("}")
a(f".soc-copy p {{ margin: 0 0 {LEADING/F_COPY:.4f}em; }}")
a(".soc-copy p:last-child { margin-bottom: 0; }")
a(".soc-copy mark {")
a('  background: url("../assets/social-highlighter.png") center / 100% 100% no-repeat;')
a("  color: inherit; padding: 0.08em 0.1em;")
a("  box-decoration-break: clone; -webkit-box-decoration-break: clone;")
a("}")
a(f".soc-phone {{ left: {X(PHONE[0])}; top: {Y(PHONE[1])}; "
  f"width: {X(PHONE[2])}; height: {Y(PHONE[3])}; }}")

open(os.path.join(ROOT, "css", "social-layout.css"), "w", encoding="utf-8").write("\n".join(o) + "\n")
print(f"box scale K = {K:.4f}  (portrait {225*K:.0f}x{P_H:.0f}, landscape {578*K:.0f}x{L_H:.0f})")
print(f"brand gap {BRAND_GAP:.1f}px, personal gap {PERSONAL_GAP:.1f}px")
print(f"brand row  : {brand[0][0]:.0f} .. {brand[-1][0]+brand[-1][1]:.0f}")
print(f"personal   : {personal[0][0]:.0f} .. {personal[-1][0]+personal[-1][1]:.0f}")
print(f"'en espanol' centred at x{esp_c:.0f} (over box 3)")
print("wrote css/social-layout.css")
